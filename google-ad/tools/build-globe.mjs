// Build-time helper: turns Natural Earth land (world-atlas 110m TopoJSON) into a list of
// [lat, lon] dots on a Fibonacci sphere, so the globe shot needs no map data at runtime.
//   node tools/build-globe.mjs <path-to-node_modules-with-world-atlas-and-topojson-client>
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const mods = process.argv[2];
const require = createRequire(mods + '/');
const topo = require('topojson-client');
const world = require('world-atlas/land-110m.json');
const land = topo.feature(world, world.objects.land);
const polys = [];
for (const f of land.features) {
  const g = f.geometry;
  const list = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const p of list) polys.push(p);
}
function inRing(x, y, ring) {
  let ins = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) ins = !ins;
  }
  return ins;
}
function isLand(lon, lat) {
  for (const p of polys) {
    if (inRing(lon, lat, p[0])) {
      let hole = false;
      for (let k = 1; k < p.length; k++) if (inRing(lon, lat, p[k])) hole = true;
      if (!hole) return true;
    }
  }
  return false;
}
const N = 16000, out = [];
const ga = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const lat = Math.asin(y) * 180 / Math.PI;
  let lon = ((i * ga) * 180 / Math.PI) % 360;
  if (lon > 180) lon -= 360;
  if (lat < -60) continue; // skip Antarctica clutter
  if (isLand(lon, lat)) out.push([+lat.toFixed(2), +lon.toFixed(2)]);
}
writeFileSync(new URL('../src/data/land-dots.js', import.meta.url),
  `// Generated by tools/build-globe.mjs from Natural Earth (public domain) via world-atlas.\n` +
  `export const LAND_DOTS = ${JSON.stringify(out)};\n`);
console.log('land dots', out.length);
